#!/usr/bin/env bash
# =====================================================================
#  10_impact_monitoring.sh - the 2-minute uptime + firewall watchdog.
#  Every run: restart scored services that are down, re-assert the
#  firewall if it was flushed OR modified, diff listening ports, and
#  check critical-file integrity against the 05 baseline.
#  ATT&CK: Impact (TA0040) - service stop / defacement / firewall tamper.
#  Installed via root crontab AND /etc/cron.d (fallback); overlap-locked.
# =====================================================================
[ -n "${BASH_VERSION:-}" ] || { echo "Run with bash: sudo bash $0" >&2; exit 1; }
_ccdc_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
. "$_ccdc_dir/common.sh" || { echo "common.sh missing next to $0" >&2; exit 1; }
. "$_ccdc_dir/05_defense_evasion_logging.sh" || { echo "05_defense_evasion_logging.sh missing next to $0" >&2; exit 1; }

WATCHDOG=/usr/local/sbin/ccdc_watchdog.sh
REASSERT=/usr/local/sbin/ccdc_reassert_firewall.sh
SERVICES_TO_WATCH=()

derive_watch_services() {
    readme_load_saved || return 1
    local svc unit out=()
    for svc in "${CCDC_README_SERVICES[@]}"; do
        [ "${need[$svc]:-no}" = yes ] || continue
        for unit in ${CCDC_SVC_UNITS[$svc]:-}; do
            svc_exists "$unit" && { out+=("$unit"); break; }
        done
    done
    echo "${out[*]}"
}

write_reassert_helper() {
    mkdir -p /usr/local/sbin
    cat > "$REASSERT" <<EOF
#!/usr/bin/env bash
# generated by 10_impact_monitoring.sh - re-applies the CCDC firewall if it was flushed or modified
STATE="$CCDC_STATE"
RELOAD=/usr/local/sbin/ccdc_firewall_reload.sh
$(declare -f fw_signature)
B=\$(cat "\$STATE/firewall_backend" 2>/dev/null)
[ -n "\$B" ] || exit 0
[ -f "\$STATE/fw_signature.cksum" ] || exit 0
cur=\$(fw_signature "\$B" | cksum)
saved=\$(cat "\$STATE/fw_signature.cksum")
if [ "\$cur" != "\$saved" ]; then
    echo "\$(date) -- FIREWALL CHANGED/FLUSHED (\$B) - restoring saved ruleset"
    fw_signature "\$B" > "\$STATE/fw_tampered_\$(date +%Y%m%d_%H%M%S).txt" 2>&1
    if [ -x "\$RELOAD" ] && "\$RELOAD"; then
        fw_signature "\$B" | cksum > "\$STATE/fw_signature.cksum"
    else
        echo "\$(date) -- FIREWALL RESTORE FAILED - re-run 08_lateral_movement.sh and 09_c2_and_exfil.sh by hand"
    fi
fi
EOF
    chmod 700 "$REASSERT"
    log "Firewall reassert helper installed at $REASSERT"
    [ -x /usr/local/sbin/ccdc_firewall_reload.sh ] || warn "No firewall reload helper yet - run 08_lateral_movement.sh so the watchdog has something to restore."
}

write_watchdog() {
    local dirs
    dirs=$(_integrity_dirs)
    cat > "$WATCHDOG" <<EOF
#!/usr/bin/env bash
# CCDC uptime + firewall watchdog - run every 2 min via cron (generated by 10_impact_monitoring.sh)
LOG="$CCDC_LOGS/watchdog.log"
STATE="$CCDC_STATE"
SERVICES="${SERVICES_TO_WATCH[*]}"
INTEGRITY_DIRS="$dirs"
LOCK="\$STATE/watchdog.lock"

if ! mkdir "\$LOCK" 2>/dev/null; then
    [ -n "\$(find "\$LOCK" -maxdepth 0 -mmin +10 2>/dev/null)" ] && rmdir "\$LOCK" 2>/dev/null && mkdir "\$LOCK" 2>/dev/null || exit 0
fi
trap 'rmdir "\$LOCK" 2>/dev/null' EXIT
echo "\$(date) -- watchdog run" >> "\$LOG"

for svc in \$SERVICES; do
    if [ -d /run/systemd/system ] && command -v systemctl >/dev/null 2>&1; then
        if ! systemctl is-active --quiet "\$svc"; then
            systemctl restart "\$svc" 2>>"\$LOG"
            echo "\$(date) -- \$svc was DOWN, restarted (now: \$(systemctl is-active "\$svc" 2>/dev/null))" >> "\$LOG"
            echo "\$(date +%s) \$svc" >> "\$STATE/watchdog_restarts"
        fi
    elif command -v rc-service >/dev/null 2>&1; then
        if ! rc-service "\$svc" status >/dev/null 2>&1; then
            rc-service "\$svc" restart >>"\$LOG" 2>&1
            echo "\$(date) -- \$svc was DOWN, restarted" >> "\$LOG"
            echo "\$(date +%s) \$svc" >> "\$STATE/watchdog_restarts"
        fi
    else
        if ! service "\$svc" status >/dev/null 2>&1; then
            service "\$svc" restart >>"\$LOG" 2>&1
            echo "\$(date) -- \$svc was DOWN, restarted" >> "\$LOG"
            echo "\$(date +%s) \$svc" >> "\$STATE/watchdog_restarts"
        fi
    fi
done

# flapping = someone keeps killing it
if [ -f "\$STATE/watchdog_restarts" ]; then
    now=\$(date +%s)
    awk -v n="\$now" '\$1 > n - 1800 {c[\$2]++} END {for (s in c) if (c[s] >= 3) print s, c[s]}' "\$STATE/watchdog_restarts" |
        while read -r s c; do echo "\$(date) -- FLAPPING: \$s restarted \$c times in 30 min - someone is killing it, go hunt" >> "\$LOG"; done
fi

# re-assert firewall in case something flushed or edited the rules
[ -x $REASSERT ] && $REASSERT >> "\$LOG" 2>&1

# listening-port diff so new backdoors stand out between runs
if command -v ss >/dev/null 2>&1; then ss -tuln 2>/dev/null; else netstat -tuln 2>/dev/null; fi | awk 'NR>1 {print \$1, \$5}' | sort -u > "\$STATE/ports_now"
if [ -f "\$STATE/ports_prev" ]; then
    if ! diff "\$STATE/ports_prev" "\$STATE/ports_now" > "\$STATE/ports_diff"; then
        echo "\$(date) -- LISTENING PORTS CHANGED:" >> "\$LOG"
        cat "\$STATE/ports_diff" >> "\$LOG"
    fi
fi
cp "\$STATE/ports_now" "\$STATE/ports_prev"

# critical-file integrity vs. 05 baseline; only log when the set of changes changes
if [ -f "\$STATE/integrity_baseline.sha256" ]; then
    { if command -v sha256sum >/dev/null 2>&1; then sha256sum -c "\$STATE/integrity_baseline.sha256" 2>/dev/null
      else shasum -a 256 -c "\$STATE/integrity_baseline.sha256" 2>/dev/null; fi | grep -v ': OK\$'
      for d in \$INTEGRITY_DIRS; do [ -d "\$d" ] && find "\$d" -maxdepth 1 -type f 2>/dev/null; done | sort | comm -13 "\$STATE/integrity_dirlist.txt" - 2>/dev/null | sed 's/^/NEW FILE: /'
    } > "\$STATE/integrity_now.txt"
    if [ -s "\$STATE/integrity_now.txt" ] && ! cmp -s "\$STATE/integrity_now.txt" "\$STATE/integrity_last_alert.txt"; then
        echo "\$(date) -- INTEGRITY CHANGES vs baseline:" >> "\$LOG"
        cat "\$STATE/integrity_now.txt" >> "\$LOG"
        cp "\$STATE/integrity_now.txt" "\$STATE/integrity_last_alert.txt"
    fi
fi
EOF
    chmod 700 "$WATCHDOG"
}

install_watchdog_cron() {
    ( crontab -l 2>/dev/null | grep -v ccdc_watchdog.sh ; echo "*/2 * * * * $WATCHDOG" ) | crontab -
    # fallback for distros where root crontab is finicky
    if [ -d /etc/cron.d ]; then
        echo "*/2 * * * * root $WATCHDOG" > /etc/cron.d/ccdc_watchdog
        chmod 644 /etc/cron.d/ccdc_watchdog
    fi
    local c
    for c in cron crond cronie; do
        if svc_exists "$c"; then svc_enable_now "$c"; break; fi
    done
    case $INIT_SYS in
        openrc) rc-update add crond default >/dev/null 2>&1; rc-service crond start >/dev/null 2>&1 ;;
    esac
}

setup_monitoring() {
    local suggestion list
    suggestion=$(derive_watch_services 2>/dev/null)
    if ccdc_noninteractive; then
        list=${CCDC_WATCH_SERVICES:-$suggestion}
    else
        echo "List the services to watch (systemd/OpenRC unit names), space separated."
        echo "Example: sshd apache2 mysql${suggestion:+   (README suggests: $suggestion)}"
        read -r -p "> " list || list=""
        [ -z "$list" ] && list=$suggestion
    fi
    read -r -a SERVICES_TO_WATCH <<< "$list"
    [ ${#SERVICES_TO_WATCH[@]} -eq 0 ] && warn "No services to watch - watchdog will only guard the firewall, ports, and integrity."

    write_reassert_helper
    write_watchdog
    install_watchdog_cron
    echo "${SERVICES_TO_WATCH[*]}" > "$CCDC_STATE/watch_services"

    if ask "Refresh the critical-file integrity baseline now (recommended right after hardening)?" CCDC_REFRESH_BASELINE yes; then
        integrity_baseline
    fi
    "$WATCHDOG"
    log "Watchdog installed, running every 2 min: $WATCHDOG (watching: ${SERVICES_TO_WATCH[*]:-none}) -> $CCDC_LOGS/watchdog.log"
}

watchdog_status() {
    echo "Cron entries:"
    crontab -l 2>/dev/null | grep ccdc_watchdog | sed 's/^/  /'
    [ -f /etc/cron.d/ccdc_watchdog ] && sed 's/^/  /' /etc/cron.d/ccdc_watchdog
    echo "Watching: $(cat "$CCDC_STATE/watch_services" 2>/dev/null)"
    echo "Last 30 watchdog log lines ($CCDC_LOGS/watchdog.log):"
    tail -n 30 "$CCDC_LOGS/watchdog.log" 2>/dev/null | sed 's/^/  /'
}

remove_watchdog() {
    ask "Remove the watchdog cron entries (scripts stay in /usr/local/sbin)?" || return 0
    crontab -l 2>/dev/null | grep -v ccdc_watchdog.sh | crontab -
    rm -f /etc/cron.d/ccdc_watchdog
    log "Watchdog cron entries removed"
}

impact_monitoring_auto() {
    setup_monitoring
    return 0
}

impact_monitoring_actions() {
    cat <<'EOF'
  auto      install watchdog (services from CCDC_WATCH_SERVICES or README answers) + refresh baseline
  setup     same as auto
  status    show cron entries + last watchdog log lines
  run       run the watchdog once now
  remove    remove the watchdog cron entries (post-competition)
EOF
}

impact_monitoring_run_action() {
    case $1 in
        auto|setup) setup_monitoring ;;
        status) watchdog_status ;;
        run) [ -x "$WATCHDOG" ] && "$WATCHDOG" && tail -n 15 "$CCDC_LOGS/watchdog.log" ;;
        remove) remove_watchdog ;;
        *) err "Unknown action: $1"; impact_monitoring_actions; return 2 ;;
    esac
}

impact_monitoring_menu() {
    ccdc_menu "10_impact_monitoring.sh - Impact / Uptime Watchdog" \
        "Setup uptime watchdog (every 2 min)" setup_monitoring \
        "Watchdog status / recent log" watchdog_status \
        "Remove watchdog cron entries" remove_watchdog
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
    ccdc_main impact_monitoring "$@"
fi
